function translate(lang,key,vars){
    const table=(lang==="hi"&&dictionaries.hi)||dictionaries.en;
    let s=table[key]||dictionaries.en[key]||key;
    if(vars){
        for(const k in vars){
            s=s.split(`{${k}}`).join(vars[k]);
        }
    }
    return s;
}

